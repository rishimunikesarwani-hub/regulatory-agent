"""Shared structural adapter interfaces. AWS implementations belong to T8."""
from pathlib import Path
from typing import Protocol, runtime_checkable

from .contracts import ModelReply, RegulatoryRequest, RetrievalResult, Snapshot


@runtime_checkable
class Records(Protocol):
    def create_case(self, owner: str, case: str, profile: dict) -> None: ...
    def authorize(self, owner: str, case: str) -> None: ...
    def put(self, owner: str, case: str, kind: str, identity: str, body: dict) -> None: ...
    def get(self, owner: str, case: str, kind: str, identity: str) -> dict: ...
    def save_snapshot(self, owner: str, snapshot: Snapshot) -> None: ...


@runtime_checkable
class Storage(Protocol):
    def put(self, owner: str, case: str, key: str, data: bytes) -> None: ...
    def read(self, owner: str, case: str, key: str) -> bytes: ...


@runtime_checkable
class Jobs(Protocol):
    def enqueue(self, owner: str, case: str, snapshot_id: str, key: str) -> dict: ...
    def read_job(self, owner: str, case: str, identity: str) -> dict: ...
    def claim(self, owner: str, case: str, identity: str, now: float | None = None) -> str | None: ...
    def reserve(self, owner: str, case: str, identity: str, token: str, kind: str, now: float | None = None) -> int: ...
    def save_stage(self, owner: str, case: str, identity: str, token: str, stage: str, output: dict, now: float | None = None) -> None: ...
    def finalize(self, owner: str, case: str, identity: str, token: str, state: str, unchecked: list[str], reason: str | None = None, now: float | None = None) -> None: ...


@runtime_checkable
class Model(Protocol):
    def dispatch(self, store: Jobs, owner: str, case: str, identity: str, token: str, request: dict, now: float | None = None) -> ModelReply: ...


@runtime_checkable
class RegulatoryRetrieval(Protocol):
    def fetch(self, request: RegulatoryRequest, store: Jobs, owner: str, case: str, identity: str, token: str, now: float | None = None) -> RetrievalResult: ...
